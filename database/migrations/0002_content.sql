-- Content: media, pages and their sections, products, the blog and menus.

CREATE TABLE media_folders (
  id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name       VARCHAR(120) NOT NULL,
  parent_id  BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_media_folders_parent (parent_id),
  CONSTRAINT fk_media_folders_parent FOREIGN KEY (parent_id) REFERENCES media_folders (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE media (
  id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  folder_id      BIGINT UNSIGNED NULL,
  filename       VARCHAR(255) NOT NULL,
  storage_key    VARCHAR(255) NOT NULL,
  url            VARCHAR(1000) NOT NULL,
  provider       VARCHAR(10)  NOT NULL DEFAULT 'local',
  mime_type      VARCHAR(100) NOT NULL,
  kind           ENUM('IMAGE','VIDEO','DOCUMENT','OTHER') NOT NULL DEFAULT 'IMAGE',
  size           INT UNSIGNED NOT NULL,
  width          INT UNSIGNED NULL,
  height         INT UNSIGNED NULL,
  alt_text       VARCHAR(255) NULL,
  title          VARCHAR(255) NULL,
  caption        TEXT NULL,
  description    TEXT NULL,
  uploaded_by_id BIGINT UNSIGNED NULL,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at     DATETIME NULL,
  UNIQUE KEY uq_media_storage_key (storage_key),
  KEY idx_media_folder (folder_id),
  KEY idx_media_kind (kind),
  KEY idx_media_created (created_at),
  CONSTRAINT fk_media_folder FOREIGN KEY (folder_id) REFERENCES media_folders (id) ON DELETE SET NULL,
  CONSTRAINT fk_media_uploader FOREIGN KEY (uploaded_by_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

