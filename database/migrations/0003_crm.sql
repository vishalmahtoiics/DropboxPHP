-- Lead capture and CRM: lead magnets, popups, submissions, leads, customers.

CREATE TABLE lead_magnets (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  title             VARCHAR(200) NOT NULL,
  slug              VARCHAR(160) NOT NULL,
  kind              ENUM('EBOOK','PDF','GUIDE','CHECKLIST','WHITEPAPER','DEMO','CONSULTATION','OFFER') NOT NULL DEFAULT 'PDF',
  description       TEXT NULL,
  is_active         TINYINT(1) NOT NULL DEFAULT 1,
  image_id          BIGINT UNSIGNED NULL,
  file_id           BIGINT UNSIGNED NULL,
  external_url      VARCHAR(500) NULL,
  form_id           BIGINT UNSIGNED NULL,
  cta_label         VARCHAR(80) NOT NULL DEFAULT 'Download',
  thank_you_title   VARCHAR(200) NULL,
  thank_you_message TEXT NULL,
  download_count    INT UNSIGNED NOT NULL DEFAULT 0,
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at        DATETIME NULL,
  UNIQUE KEY uq_lead_magnets_slug (slug),
  CONSTRAINT fk_lm_image FOREIGN KEY (image_id) REFERENCES media (id) ON DELETE SET NULL,
  CONSTRAINT fk_lm_file FOREIGN KEY (file_id) REFERENCES media (id) ON DELETE SET NULL,
  CONSTRAINT fk_lm_form FOREIGN KEY (form_id) REFERENCES forms (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE popups (
  id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  country_id     BIGINT UNSIGNED NULL,
  name           VARCHAR(160) NOT NULL,
  type           ENUM('OFFER','IMAGE','LEAD_FORM','NEWSLETTER','PRODUCT','LEAD_MAGNET') NOT NULL DEFAULT 'LEAD_FORM',
  is_active      TINYINT(1) NOT NULL DEFAULT 0,
  heading        VARCHAR(255) NULL,
  body           TEXT NULL,
  image_id       BIGINT UNSIGNED NULL,
  form_id        BIGINT UNSIGNED NULL,
  lead_magnet_id BIGINT UNSIGNED NULL,
  cta_label      VARCHAR(80) NULL,
  cta_url        VARCHAR(500) NULL,
  `trigger`      ENUM('IMMEDIATE','DELAY','SCROLL','EXIT_INTENT','CLICK') NOT NULL DEFAULT 'DELAY',
  delay_seconds  INT NOT NULL DEFAULT 5,
  scroll_percent INT NOT NULL DEFAULT 50,
  device         ENUM('ALL','DESKTOP','MOBILE') NOT NULL DEFAULT 'ALL',
  frequency_days INT NOT NULL DEFAULT 7,
  starts_at      DATETIME NULL,
  ends_at        DATETIME NULL,
  url_patterns   JSON NULL,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at     DATETIME NULL,
  KEY idx_popups_active (is_active),
  CONSTRAINT fk_popups_country FOREIGN KEY (country_id) REFERENCES countries (id) ON DELETE SET NULL,
  CONSTRAINT fk_popups_image FOREIGN KEY (image_id) REFERENCES media (id) ON DELETE SET NULL,
  CONSTRAINT fk_popups_form FOREIGN KEY (form_id) REFERENCES forms (id) ON DELETE SET NULL,
  CONSTRAINT fk_popups_lm FOREIGN KEY (lead_magnet_id) REFERENCES lead_magnets (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE customers (
  id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name           VARCHAR(160) NOT NULL,
  company        VARCHAR(200) NULL,
  email          VARCHAR(254) NOT NULL,
  phone          VARCHAR(40) NULL,
  website        VARCHAR(500) NULL,
  address        TEXT NULL,
  gstin          VARCHAR(30) NULL,
  status         ENUM('PROSPECT','ACTIVE','INACTIVE','FORMER') NOT NULL DEFAULT 'PROSPECT',
  assigned_to_id BIGINT UNSIGNED NULL,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at     DATETIME NULL,
  KEY idx_customers_email (email),
  KEY idx_customers_status (status),
  CONSTRAINT fk_customers_assignee FOREIGN KEY (assigned_to_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE leads (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  country_id         BIGINT UNSIGNED NOT NULL,
  name               VARCHAR(160) NOT NULL,
  email              VARCHAR(254) NOT NULL,
  phone              VARCHAR(40) NULL,
  company            VARCHAR(200) NULL,
  job_title          VARCHAR(120) NULL,
  message            TEXT NULL,
  status             ENUM('NEW','CONTACTED','QUALIFIED','PROPOSAL','NEGOTIATION','WON','LOST','SPAM') NOT NULL DEFAULT 'NEW',
  priority           ENUM('LOW','MEDIUM','HIGH') NOT NULL DEFAULT 'MEDIUM',
  pipeline_order     INT NOT NULL DEFAULT 0,
  source             VARCHAR(120) NULL,
  campaign           VARCHAR(160) NULL,
  cta_label          VARCHAR(160) NULL,
  cta_location       VARCHAR(160) NULL,
  utm_source         VARCHAR(160) NULL,
  utm_medium         VARCHAR(160) NULL,
  utm_campaign       VARCHAR(160) NULL,
  utm_term           VARCHAR(160) NULL,
  utm_content        VARCHAR(160) NULL,
  first_utm_source   VARCHAR(160) NULL,
  first_utm_medium   VARCHAR(160) NULL,
  first_utm_campaign VARCHAR(160) NULL,
  first_utm_term     VARCHAR(160) NULL,
  first_utm_content  VARCHAR(160) NULL,
  first_landing_url  VARCHAR(1000) NULL,
  first_touch_at     DATETIME NULL,
  referrer           VARCHAR(1000) NULL,
  landing_url        VARCHAR(1000) NULL,
  user_agent         VARCHAR(500) NULL,
  ip_hash            CHAR(32) NULL,
  product_id         BIGINT UNSIGNED NULL,
  landing_page_id    BIGINT UNSIGNED NULL,
  blog_post_id       BIGINT UNSIGNED NULL,
  form_id            BIGINT UNSIGNED NULL,
  lead_magnet_id     BIGINT UNSIGNED NULL,
  assigned_to_id     BIGINT UNSIGNED NULL,
  customer_id        BIGINT UNSIGNED NULL,
  marketing_consent  TINYINT(1) NOT NULL DEFAULT 0,
  follow_up_at       DATETIME NULL,
  lost_reason        TEXT NULL,
  value              DECIMAL(12,2) NULL,
  created_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at         DATETIME NULL,
  KEY idx_leads_country (country_id, created_at),
  KEY idx_leads_status (status, pipeline_order),
  KEY idx_leads_email (email),
  KEY idx_leads_assignee (assigned_to_id),
  KEY idx_leads_created (created_at),
  KEY idx_leads_deleted (deleted_at),
  KEY idx_leads_source (source),
  CONSTRAINT fk_leads_country FOREIGN KEY (country_id) REFERENCES countries (id) ON DELETE RESTRICT,
  CONSTRAINT fk_leads_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE SET NULL,
  CONSTRAINT fk_leads_page FOREIGN KEY (landing_page_id) REFERENCES pages (id) ON DELETE SET NULL,
  CONSTRAINT fk_leads_post FOREIGN KEY (blog_post_id) REFERENCES blog_posts (id) ON DELETE SET NULL,
  CONSTRAINT fk_leads_form FOREIGN KEY (form_id) REFERENCES forms (id) ON DELETE SET NULL,
  CONSTRAINT fk_leads_lm FOREIGN KEY (lead_magnet_id) REFERENCES lead_magnets (id) ON DELETE SET NULL,
  CONSTRAINT fk_leads_assignee FOREIGN KEY (assigned_to_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_leads_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE form_submissions (
  id           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  form_id      BIGINT UNSIGNED NOT NULL,
  country_id   BIGINT UNSIGNED NULL,
  lead_id      BIGINT UNSIGNED NULL,
  data         JSON NOT NULL,
  field_labels JSON NULL,
  form_name    VARCHAR(160) NULL,
  ip_hash      CHAR(32) NULL,
  user_agent   VARCHAR(500) NULL,
  referrer     VARCHAR(1000) NULL,
  page_url     VARCHAR(1000) NULL,
  created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_form_submissions_form (form_id, created_at),
  CONSTRAINT fk_fs_form FOREIGN KEY (form_id) REFERENCES forms (id) ON DELETE CASCADE,
  CONSTRAINT fk_fs_country FOREIGN KEY (country_id) REFERENCES countries (id) ON DELETE SET NULL,
  CONSTRAINT fk_fs_lead FOREIGN KEY (lead_id) REFERENCES leads (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE lead_notes (
  id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  lead_id    BIGINT UNSIGNED NOT NULL,
  author_id  BIGINT UNSIGNED NULL,
  body       TEXT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_lead_notes_lead (lead_id, created_at),
  CONSTRAINT fk_ln_lead FOREIGN KEY (lead_id) REFERENCES leads (id) ON DELETE CASCADE,
  CONSTRAINT fk_ln_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE lead_activities (
  id         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  lead_id    BIGINT UNSIGNED NOT NULL,
  type       ENUM('CREATED','STATUS_CHANGED','ASSIGNED','NOTE_ADDED','EMAIL_SENT','CALL_LOGGED','MEETING_LOGGED','FOLLOW_UP_SET','UPDATED','CONVERTED') NOT NULL,
  actor_id   BIGINT UNSIGNED NULL,
  summary    TEXT NOT NULL,
  meta       JSON NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_la_lead (lead_id, created_at),
  CONSTRAINT fk_la_lead FOREIGN KEY (lead_id) REFERENCES leads (id) ON DELETE CASCADE,
  CONSTRAINT fk_la_actor FOREIGN KEY (actor_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE customer_notes (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  customer_id BIGINT UNSIGNED NOT NULL,
  author_id   BIGINT UNSIGNED NULL,
  body        TEXT NOT NULL,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
