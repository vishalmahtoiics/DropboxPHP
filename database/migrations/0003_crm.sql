  CONSTRAINT fk_cn_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
  CONSTRAINT fk_cn_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE customer_products (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  customer_id BIGINT UNSIGNED NOT NULL,
  product_id  BIGINT UNSIGNED NOT NULL,
  quantity    INT NOT NULL DEFAULT 1,
  seats       INT NULL,
  unit_price  DECIMAL(12,2) NULL,
  starts_at   DATE NULL,
  renews_at   DATE NULL,
  notes       TEXT NULL,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_cp_customer (customer_id),
  CONSTRAINT fk_cp_customer FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE,
  CONSTRAINT fk_cp_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Evidence of what a visitor agreed to, kept with the exact notice text.
CREATE TABLE consent_records (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  lead_id            BIGINT UNSIGNED NULL,
  submission_id      BIGINT UNSIGNED NULL,
  country_id         BIGINT UNSIGNED NULL,
  email              VARCHAR(254) NULL,
  enquiry_consent    TINYINT(1) NOT NULL DEFAULT 0,
  marketing_consent  TINYINT(1) NOT NULL DEFAULT 0,
  terms_accepted     TINYINT(1) NOT NULL DEFAULT 0,
  lawful_basis       VARCHAR(30) NOT NULL DEFAULT 'CONSENT',
  notice_text        TEXT NULL,
  page_url           VARCHAR(1000) NULL,
  ip_hash            CHAR(32) NULL,
  withdrawn_at       DATETIME NULL,
  created_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_consent_lead (lead_id),
  KEY idx_consent_email (email),
  CONSTRAINT fk_consent_lead FOREIGN KEY (lead_id) REFERENCES leads (id) ON DELETE SET NULL,
  CONSTRAINT fk_consent_submission FOREIGN KEY (submission_id) REFERENCES form_submissions (id) ON DELETE SET NULL,
  CONSTRAINT fk_consent_country FOREIGN KEY (country_id) REFERENCES countries (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
